/* =========================================================================
   OFFLINE AUDIO GENERATION — ElevenLabs "Alice"
   Usage:  node scripts/generate_audio.js           (skips files that exist)
           node scripts/generate_audio.js --force   (re-generate everything)
   • Reads phrases from src/utils/lessonScript.js (same text the UI shows)
   • Sanitizes speech phonetics for crystal clear math pronunciation
   • Applies per-style voice settings
   • Saves MP3s to public/assets/audio/ and rewrites src/utils/audioMap.js
   • Rate-limited with auto-retry on 429
   Requires Node 18+ and VITE_ELEVENLABS_API_KEY in .env.local
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ALL_PHRASES } from '../src/utils/lessonScript.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const VOICE_ID = 'Xb7hH8MSUJpSbSDYk0k2';
const MODEL_ID = 'eleven_multilingual_v2';

// Same settings table as src/utils/audio.js
const STYLE_SETTINGS = {
  celebration:   { stability: 0.12, similarity_boost: 0.45, style: 0.75, use_speaker_boost: true },
  encouragement: { stability: 0.16, similarity_boost: 0.50, style: 0.65, use_speaker_boost: true },
  question:      { stability: 0.20, similarity_boost: 0.55, style: 0.55, use_speaker_boost: true },
  emphasis:      { stability: 0.16, similarity_boost: 0.50, style: 0.60, use_speaker_boost: true },
  thinking:      { stability: 0.24, similarity_boost: 0.60, style: 0.35, use_speaker_boost: true },
  statement:     { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true },
  instruction:   { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true }
};

/** Convert math notation and symbols into natural, spoken English for ElevenLabs */
export function prepareSpokenText(text) {
  return text
    .replace(/cm²/g, 'square centimetres')
    .replace(/m²/g, 'square metres')
    .replace(/\bcm\b/g, 'centimetres')
    .replace(/\bm\b/g, 'metres')
    .replace(/π\s*=\s*22\/7/g, 'taking pi equal to 22 over 7')
    .replace(/π\s*=\s*3\.14/g, 'taking pi equal to 3.14')
    .replace(/π/g, 'pi')
    .replace(/×/g, 'times')
    .replace(/÷/g, 'divided by')
    .replace(/\$(\d+)/g, '$1 dollars')
    .replace(/²/g, ' squared')
    .replace(/½/g, 'half')
    .replace(/√(\d+)/g, 'square root of $1')
    .replace(/lw \+ lh \+ wh/g, 'l w plus l h plus w h')
    .replace(/2πr² \+ 2πrh/g, '2 pi r squared plus 2 pi r h')
    .replace(/2πrh/g, '2 pi r h')
    .replace(/2πr/g, '2 pi r')
    .replace(/πr²/g, 'pi r squared')
    .replace(/\bSA\b/g, 'surface area');
}

function readEnvKey() {
  if (process.env.VITE_ELEVENLABS_API_KEY) return process.env.VITE_ELEVENLABS_API_KEY;
  for (const f of ['.env.local', '.env']) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^\s*VITE_ELEVENLABS_API_KEY\s*=\s*"?([^"\r\n]+)"?/m);
    if (m) return m[1].trim();
  }
  return '';
}

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 50);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function saveMap(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function main() {
  const force = process.argv.includes('--force');
  const apiKey = readEnvKey();
  if (!apiKey) {
    console.error('✖ VITE_ELEVENLABS_API_KEY not found in .env.local');
    process.exit(1);
  }
  fs.mkdirSync(OUT_DIR, { recursive: true });

  // De-duplicate by exact text (first style wins)
  const seen = new Set();
  const phrases = ALL_PHRASES.filter(p => {
    if (!p.text || seen.has(p.text)) return false;
    seen.add(p.text);
    return true;
  });

  console.log(`Starting audio generation for ${phrases.length} distinct phrases...`);

  // Load existing audioMap if available
  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const existingContent = fs.readFileSync(MAP_FILE, 'utf8');
      const match = existingContent.match(/export const audioMap = (\{[\s\S]*\});/);
      if (match) map = JSON.parse(match[1]);
    } catch (e) {}
  }

  let made = 0, skipped = 0, failed = 0;

  for (const [i, p] of phrases.entries()) {
    const hash = crypto.createHash('md5').update(p.text).digest('hex').slice(0, 6);
    const fileName = `audio_${slugify(p.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    if (!force && fs.existsSync(filePath) && fs.statSync(filePath).size > 100) {
      map[p.text] = publicPath;
      skipped++;
      continue;
    }

    const s = STYLE_SETTINGS[p.style] || STYLE_SETTINGS.statement;
    const spoken = prepareSpokenText(p.text);
    process.stdout.write(`[${i + 1}/${phrases.length}] (${p.style}) ${p.text.slice(0, 55)}… `);

    let success = false;
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
          method: 'POST',
          headers: {
            'xi-api-key': apiKey,
            'Content-Type': 'application/json',
            Accept: 'audio/mpeg'
          },
          body: JSON.stringify({
            text: spoken,
            model_id: MODEL_ID,
            voice_settings: s
          })
        });

        if (res.status === 429) {
          process.stdout.write('[429 rate limit, waiting 3s] ');
          await sleep(3000);
          continue;
        }

        if (!res.ok) {
          throw new Error(`${res.status} ${await res.text()}`);
        }

        const buffer = Buffer.from(await res.arrayBuffer());
        fs.writeFileSync(filePath, buffer);
        map[p.text] = publicPath;
        made++;
        success = true;
        console.log('✔');
        break;
      } catch (e) {
        if (attempt === 2) {
          failed++;
          console.log(`✖ ${e.message.slice(0, 140)}`);
        } else {
          await sleep(1000);
        }
      }
    }

    // Periodically persist audioMap so progress is never lost
    if (made % 5 === 0) {
      saveMap(map);
    }

    await sleep(250);
  }

  saveMap(map);
  console.log(`\nFinished: generated ${made}, reused ${skipped}, failed ${failed}. audioMap.js updated.`);
  if (failed > 0) process.exitCode = 1;
}

main();
